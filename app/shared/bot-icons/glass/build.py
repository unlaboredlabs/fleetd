"""Builds the shipped bot icons: every glass being (beings.json) in every palette color (../palette.json).

    BLENDER=/path/to/blender python3 app/shared/bot-icons/glass/build.py

Blender Cycles renders each one once at 288 px (scene.py) into out/glass/, keeping renders that are already there; then
Pillow shrinks those into the WebP files the apps ship, at two sizes in points, each at 1x, 2x and 3x:
- 32 for the small places (the desktop's sidebar and chat title, the phone's chat header),
- 96 for the rest (lists, Info, settings, the picker).
It writes them to app/desktop/src/shared/botIcons/ with the faces and colors (index.ts), and the phone's map of them
(app/mobile/src/botIconFiles.ts), as React Native requires each image by name. Needs Python 3 with Pillow.
"""

import json
import os
import subprocess
import sys
from pathlib import Path

from PIL import Image

HERE = Path(__file__).resolve().parent
ICONS = HERE.parent
APP = ICONS.parent.parent
MASTERS = ICONS / "out" / "glass"
SHIPPED = APP / "desktop" / "src" / "shared" / "botIcons"
PHONE = APP / "mobile" / "src" / "botIconFiles.ts"
MASTER_PX = 288
SAMPLES = 64
SIZES = (32, 96)
QUALITY = 86

beings = json.loads((HERE / "beings.json").read_text())["beings"]
colors = json.loads((ICONS / "palette.json").read_text())["colors"]
icons = [(b["id"], c["id"]) for b in beings for c in colors]
field = {c["id"]: c["field"] for c in colors}


def render():
    MASTERS.mkdir(parents=True, exist_ok=True)
    jobs = [
        {"being": face, "color": {"field": field[color]}, "size": MASTER_PX, "samples": SAMPLES, "out": str(MASTERS / f"{face}-{color}.png")}
        for face, color in icons
        if not (MASTERS / f"{face}-{color}.png").exists()
    ]
    if not jobs:
        return
    print(f"rendering {len(jobs)} of {len(icons)}, about 40 s each on two threads", flush=True)
    listing = MASTERS / "jobs.json"
    listing.write_text(json.dumps({"jobs": jobs}))
    blender = os.environ.get("BLENDER", "blender")
    subprocess.run([blender, "-b", "--factory-startup", "-t", "2", "--python", str(HERE / "scene.py"), "--", str(listing)], check=True, stdout=subprocess.DEVNULL)


def name(face, color, pt, scale):
    return f"{face}-{color}-{pt}{'' if scale == 1 else f'@{scale}x'}.webp"


def shrink():
    SHIPPED.mkdir(parents=True, exist_ok=True)
    for old in SHIPPED.glob("*.webp"):
        old.unlink()
    for face, color in icons:
        master = Image.open(MASTERS / f"{face}-{color}.png").convert("RGBA")
        for pt in SIZES:
            for scale in (1, 2, 3):
                px = pt * scale
                small = master if px == MASTER_PX else master.resize((px, px), Image.LANCZOS)
                small.save(SHIPPED / name(face, color, pt, scale), "WEBP", quality=QUALITY, alpha_quality=100, method=6)


def modules():
    head = "// Generated by app/shared/bot-icons/glass/build.py: don't edit.\n"
    faces = ",\n".join(f'  {{ id: "{b["id"]}", name: "{b["name"]}" }}' for b in beings)
    swatches = ",\n".join(f'  {{ id: "{c["id"]}", name: "{c["name"]}", field: "{c["field"]}" }}' for c in colors)
    (SHIPPED / "index.ts").write_text(
        head
        + "// The built-in icons a project or Navi wears: a glass being (a face) on a round field of a color. The images are\n"
        + "// beside this file, `<face>-<color>-<points>[@2x|@3x].webp`, at 32 and 96 points.\n"
        + 'import type { IconColor, IconFace } from "../contracts";\n\n'
        + f"export const ICON_FACES: readonly {{ readonly id: IconFace; readonly name: string }}[] = [\n{faces},\n];\n\n"
        + f"/** Each color with its field, as the swatches show it. */\nexport const ICON_COLORS: readonly {{ readonly id: IconColor; readonly name: string; readonly field: string }}[] = [\n{swatches},\n];\n"
    )
    rel = os.path.relpath(SHIPPED, PHONE.parent)
    entries = []
    for face, color in icons:
        entries.append(f'  "{face}-{color}": [require("{rel}/{name(face, color, 32, 1)}"), require("{rel}/{name(face, color, 96, 1)}")],')
    PHONE.write_text(
        head
        + "// Each built-in icon's images, by `<face>-<color>`: its 32 and 96 point WebP, which Metro serves at the screen's scale\n"
        + "// (@2x, @3x beside them).\n"
        + "/* eslint-disable @typescript-eslint/no-require-imports */\n"
        + "export const ICON_FILES: Readonly<Record<string, readonly [number, number]>> = {\n"
        + "\n".join(entries)
        + "\n};\n"
    )


if __name__ == "__main__":
    if "--shrink" not in sys.argv:
        render()
    shrink()
    modules()
    total = sum(f.stat().st_size for f in SHIPPED.glob("*.webp"))
    print(f"{len(icons)} icons, {total // 1024} KB of WebP in {SHIPPED.relative_to(APP.parent)}")
