// Generates src/gen/migrations.ts: every hub migration in src/hub/store/migrations, in the order of their numeric
// prefixes, as text imports (`bun build --compile` embeds them). Two migrations with one prefix fail it.
//
//   bun scripts/gen.ts           writes it
//   bun scripts/gen.ts --check   writes nothing, fails when it is out of date (CI)
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";

const BUN = join(import.meta.dir, "..");
const ROOT = join(BUN, "..");
const MIGRATIONS = join(BUN, "src/hub/store/migrations");
const OUT = join(BUN, "src/gen/migrations.ts");

const files = readdirSync(MIGRATIONS)
  .filter((f) => f.endsWith(".sql"))
  .sort((a, b) => Number(a.split("_")[0]) - Number(b.split("_")[0]));
const prefixes = new Map<string, string>();
for (const f of files) {
  const prefix = f.split("_")[0] ?? "";
  if (!/^\d+$/.test(prefix)) throw new Error(`gen: migration ${f} doesn't start with a number and _`);
  const other = prefixes.get(prefix);
  if (other) throw new Error(`gen: migrations ${other} and ${f} share the prefix ${prefix}: renumber the newer one`);
  prefixes.set(prefix, f);
}

const text = `// Generated by fleetd/scripts/gen.ts. Don't edit: run \`bun run gen\`.
// The hub's migrations (bun build --compile embeds them), in the order of their prefixes.
${files.map((f, i) => `import m${i} from "../hub/store/migrations/${f}" with { type: "text" };`).join("\n")}

export const MIGRATIONS: readonly { name: string; sql: string }[] = [
${files.map((f, i) => `  { name: "${f.replace(/\.sql$/, "")}", sql: m${i} },`).join("\n")}
];
`;

const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : undefined;
if (current === text) {
  if (process.argv.includes("--check")) console.log(`src/gen/migrations.ts is current (${files.length} migrations)`);
} else if (process.argv.includes("--check")) {
  console.error(`out of date: ${relative(ROOT, OUT)}`);
  console.error("fix: cd fleetd && bun run gen, then commit the result");
  process.exit(1);
} else {
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, text);
  console.log(`wrote ${relative(ROOT, OUT)}`);
}
