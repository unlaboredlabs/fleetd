/** Every generated file: (path under CONTENT, the text it should have). */
export function build(): [string, string][] {
  const files: [string, string][] = [
    ["reference/cli.md", cliPage()],
    [AGENT_TOOLS, agentToolsPage()],
  ];
  // Regions of hand-written pages: the lines between `<!-- name -->` and `<!-- /name -->`.
  for (const [name, region, generate] of [["what-agents-are-told.md", "prompt-table", promptTable]] as const) {
    const text = readFileSync(join(ROOT, CONTENT, name), "utf8");
    try {
      files.push([name, splice(text, region, generate())]);
    } catch (error) {
      throw new Error(`${name}: ${(error as Error).message}`);
    }
  }
  return files;
}

if (import.meta.main) {
  const check = process.argv.includes("--check");
  const stale: string[] = [];
  const files = build();
  for (const [name, text] of files) {
    const path = join(ROOT, CONTENT, name);
    let saved: string | undefined;
    try {
      saved = readFileSync(path, "utf8");
    } catch {}
    if (saved === text) continue;
    if (check) {
      stale.push(name);
      continue;
    }
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, text);
  }
  if (stale.length === 0) {
    console.log(`docs: ${CONTENT}: ${files.length} generated files are current`);
  } else {
    for (const name of stale) {
      console.log(`::error file=${CONTENT}/${name}::${CONTENT}/${name} is out of date; run \`bun scripts/docs.ts\` in fleetd/ and commit it`);
    }
    process.exit(1);
  }
}
