const cell = (text: string) => sourceText(text.split(/\s+/).filter(Boolean).join(" ")).replaceAll("|", "\\|");

/** Source text as markdown that shows it literally: outside code spans, `<n>` is not an HTML tag and `*` is not
 * emphasis. */
export const sourceText = (text: string) =>
  text
    .split("`")
    .map((part, i) => (i % 2 === 1 ? part : part.replaceAll("<", "&lt;").replaceAll("*", "\\*")))
    .join("`");

/** Consecutive items that share a reason, as one row each. */
function grouped(items: [string, string][]): [string[], string][] {
  const rows: [string[], string][] = [];
  for (const [item, why] of items) {
    const last = rows.at(-1);
    if (last && last[1] === why) last[0].push(item);
    else rows.push([[item], why]);
  }
  return rows;
}

const ticked = (table: readonly (readonly [string, string])[]): [string, string][] => table.map(([t, why]) => [`\`${t}\``, why]);

