const DEFAULT = ", unless your environment or `claude.env` sets it";

function switches(): string {
  const cacheEnv = Object.fromEntries([...PROMPT_CACHE_TTL_VARS, ...[...WORKER_ENV, ...LEAD_ENV].map(([k]) => k)].map((k) => [k, ""]));
  const overlayEnv: Record<string, string> = JSON.parse(settingsOverlay(cacheEnv, {}, MODEL, [], false, false, "")).env;
  let md =
    "\n## Settings fleetd sets\n\nIn the environment of every claude fleetd starts, unless a line says otherwise. Those " +
    "marked *forced* are in fleetd's own settings for the session too, so the `env` in your Claude Code settings can't " +
    "change them.\n\n";
  const line = (names: string[], value: string, why: string) => {
    const forced = names.every((n) => n in overlayEnv) ? " (*forced*)" : "";
    md += `- ${names.map((n) => `\`${n}\``).join(", ")}${value}${forced}: ${sourceText(why)}\n`;
  };
  for (const [[name, value], why] of SUBAGENTS_OFF_ENV_WHY) line([name], ` = \`${value}\``, why);
  for (const [name, why] of SUBAGENTS_ON_ENV_WHY) line([name], " removed", why);
  line([AUTO_MEMORY_OFF_ENV[0]], ` = \`${AUTO_MEMORY_OFF_ENV[1]}\`, and \`autoMemoryEnabled: false\``, AUTO_MEMORY_OFF_WHY);
  line([HELPER_MODEL_ENV], ` = the default profile's model (\`${MODEL}\` unless you chose another)`, HELPER_MODEL_WHY);
  for (const [[name, value], why] of SESSION_ENV_WHY) line([name], ` = \`${value}\``, why);
  for (const [[name, value], why] of DEFAULT_ENV_WHY) line([name], ` = \`${value}\`${DEFAULT}`, why);
  line([...PROMPT_CACHE_TTL_VARS], DEFAULT, "How long the prompt cache lasts:");
  for (const [[role, ttl], why] of PROMPT_CACHE_TTL_WHY) md += `  - \`${ttl}\` for ${CACHE_WHO[role]}: ${sourceText(why)}\n`;
  for (const [[name, value], why] of WORKER_ENV_WHY) line([name], ` = \`${value}\` for agents${DEFAULT}`, why);
  for (const [[name, value], why] of LEAD_ENV_WHY) line([name], ` = \`${value}\` for leads`, why);
  for (const [names, why] of grouped(NESTING_VARS_WHY.map(([n, w]) => [n, w]))) line(names, " removed", why);
  return md;
}

