/** How a task of `role` is started, from the hub's own kind-to-role rule. */
function startedAs(role: AgentRole): string | undefined {
  for (const kind of ["write", "read", "review"] as TaskKind[]) {
    for (const qa of [false, true]) {
      if (phaseRole(kind, qa) !== role) continue;
      let how = `\`spawn_agent\` with kind \`${kind}\``;
      if (qa) how += " and `qa: true`";
      if (kind === "write") how += ". Gets its own worktree and branch";
      return how;
    }
  }
  return undefined;
}

