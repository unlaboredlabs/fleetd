/** The MCP server's own decoder accepts it, and every key is one the schema names. */
export function checkExample(role: Role, tool: ToolSpec, args: Json): void {
  try {
    callOf(role, tool.name, args);
  } catch (error) {
    throw new Error(`agent tools: the example for ${tool.name}: ${error instanceof Error ? error.message : String(error)}`);
  }
  const key = unknownKey(args, tool.inputSchema, "");
  if (key !== undefined) throw new Error(`agent tools: the example for ${tool.name} has ${key}, which its schema doesn't`);
}

/** The first key of `value` its schema doesn't name, by path. */
function unknownKey(value: Json, schema: Json, at: string): string | undefined {
  if (Array.isArray(value)) {
    for (const item of value) {
      const key = unknownKey(item, schema?.items, `${at}[].`);
      if (key !== undefined) return key;
    }
    return undefined;
  }
  if (!isObj(value)) return undefined;
  const variants = variantsOf(schema) ?? [schema];
  const fits = (s: Json) =>
    Object.entries(value).every(([k, v]) => isObj(s?.properties) && k in s.properties && unknownKey(v, s.properties[k], "") === undefined);
  if (variants.some(fits)) return undefined;
  const s = variants[0];
  for (const [k, v] of Object.entries(value)) {
    if (!isObj(s?.properties) || !(k in s.properties)) return `${at}${k}`;
    const key = unknownKey(v, s.properties[k], `${at}${k}.`);
    if (key !== undefined) return key;
  }
  return undefined;
}

/** Claude Code's built-in tools as the recorded version lists them, from the `system/init` lines in the runner's
 * recorded fixtures. */
function recordedTools(): string[] {
  const tools = new Set<string>();
  for (const name of readdirSync(FIXTURES)) {
    if (!name.startsWith(`claude-${RECORDED}-`) || !name.endsWith(".jsonl")) continue;
    for (const line of readFileSync(join(FIXTURES, name), "utf8").split("\n")) {
      let frame: Json;
      try {
        frame = JSON.parse(line);
      } catch {
        continue;
      }
      const msg = frame?.msg;
      if (msg?.type !== "system" || msg?.subtype !== "init" || !Array.isArray(msg.tools)) continue;
      for (const t of msg.tools) if (typeof t === "string" && !t.startsWith("mcp__")) tools.add(t);
    }
  }
  if (tools.size === 0) throw new Error(`agent tools: no claude ${RECORDED} init in ${FIXTURES}`);
  return [...tools].sort();
}

