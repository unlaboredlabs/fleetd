/** Lowercased words joined by `-`, as Starlight's heading ids are (github-slugger). */
export function slugify(text: string): string {
  let out = "";
  for (const c of text.toLowerCase()) {
    if (/^[\p{L}\p{N}_]$/u.test(c)) out += c;
    else if (out && !out.endsWith("-") && c !== "'") out += "-";
  }
  return out.replace(/-+$/, "");
}

/** Text safe in a markdown paragraph or table cell: nothing in it reads as markup. */
export const mdText = (s: string) => s.replace(/[\\`*_[\]<>|#{}]/g, (c) => `\\${c}`);

/** `text` with the lines between the region's markers replaced by `generated`. */
export function splice(text: string, region: string, generated: string): string {
  const open = `<!-- ${region} -->\n`;
  const close = `<!-- /${region} -->\n`;
  const at = text.indexOf(open);
  if (at < 0) throw new Error(`no ${JSON.stringify(open)} line`);
  const start = at + open.length;
  const end = text.indexOf(close, start);
  if (end < 0) throw new Error(`no ${JSON.stringify(close)} line after ${JSON.stringify(open)}`);
  return `${text.slice(0, start)}\n${generated}\n${text.slice(end)}`;
}

const trimEnd = (s: string) => `${s.trimEnd()}\n`;
const codeList = (items: Iterable<string>) => [...items].map((i) => `\`${i}\``).join(", ");

/** Object keys sorted at every level, as the generator has always printed JSON. */
function sorted(v: Json): Json {
  if (Array.isArray(v)) return v.map(sorted);
  if (v === null || typeof v !== "object") return v;
  return Object.fromEntries(Object.keys(v).sort().map((k) => [k, sorted(v[k])]));
}

