function who(): string {
  for (const [role] of AGENT_KINDS) {
    const started = (["write", "read", "review"] as TaskKind[]).some((kind) => [false, true].some((qa) => phaseRole(kind, qa) === role));
    if (!started) throw new Error(`agent tools: nothing starts a ${role}`);
  }
  if (!SPAWN_OPS.every((op) => allowed({ kind: "lead" }, op)) || SPAWN_OPS.some((op) => allowed(TASK_CALLER, op))) {
    throw new Error("agent tools: the page says only a lead starts agents, and the hub's policy no longer agrees");
  }
  let md = "\n## Who gets which tools\n\n";
  md += "- **The lead**: one per bot. It talks with you in the bot's chat and starts the bot's agents.\n";
  md += `- **Agents**: ${AGENT_KINDS.map(([, words]) => words).join("; ")}. They can't start agents of their own.\n\n`;
  md += "Each tool below says when only one of them gets it.\n";
  return md;
}

function tools(lead: ToolSpec[], task: ToolSpec[]): string {
  const offered = new Set([...lead, ...task].map((t) => t.name));
  const described = TOOL_GROUPS.flatMap(([, items]) => items.map(([name]) => name));
  const missing = [...offered].filter((n) => !described.includes(n));
  if (missing.length) throw new Error(`agent tools: say what ${missing.join(", ")} does in TOOL_GROUPS (scripts/docs.ts)`);
  const gone = described.filter((n) => !offered.has(n));
  if (gone.length) throw new Error(`agent tools: TOOL_GROUPS names ${gone.join(", ")}, which no session is offered`);
  const twice = described.filter((n, i) => described.indexOf(n) !== i);
  if (twice.length) throw new Error(`agent tools: TOOL_GROUPS names ${twice.join(", ")} twice`);
  let md = "\n## fleetd's tools\n";
  for (const [title, items] of TOOL_GROUPS) {
    md += `\n### ${title}\n\n`;
    for (const [name, words] of items) {
      const [byLead, byTask] = [whoMayCall(name, "lead"), whoMayCall(name, "worker")];
      const only = byLead && !byTask ? " Lead only." : byTask && !byLead ? " Agents only." : "";
      // Each tool keeps its own anchor (#chat_file), which other pages link to.
      md += `- <span id="${name}"></span>\`${name}\`: ${words}${only}\n`;
    }
  }
  return md;
}

/** Whether `role` is offered the tool and the hub lets it make the call. A browser call never reaches the hub's
 * policy: the session's own node answers it. */
function whoMayCall(name: string, role: Role): boolean {
  const tool = toolsFor(role).find((t) => t.name === name);
  return tool !== undefined && (tool.browser || allowed(role === "lead" ? { kind: "lead" } : TASK_CALLER, tool.op));
}

const schemaDefs = (name: string): Json => JSON.parse(readFileSync(join(SCHEMA, `${name}.json`), "utf8")).$defs;

const orList = (items: string[]) => (items.length < 2 ? items.join("") : `${items.slice(0, -1).join(", ")} or ${items.at(-1)}`);

/** `14400` -> "4 hours". */
const duration = (seconds: number) =>
  seconds % 3600 === 0 ? `${seconds / 3600} hour${seconds === 3600 ? "" : "s"}` : `${Math.round(seconds / 60)} minutes`;

function limits(lead: ToolSpec[], task: ToolSpec[]): string {
  // Every tool a task is offered: its lead calls, which the hub allows by WORKER_OPS, and its browser calls, which its
  // node answers.
  const refused = task.find((t) => !t.browser && !WORKER_OPS.includes(t.op));
  if (refused) throw new Error(`agent tools: a task is offered ${refused.name}, which the hub refuses it`);
  if (MAX_DEPTH !== 1) throw new Error("agent tools: the page says agents can't start agents; MAX_DEPTH changed");
  const spawners = SPAWN_OPS.map((op) => lead.find((t) => t.op === op)?.name);
  if (spawners.some((n) => n === undefined)) throw new Error("agent tools: a hub policy op has no MCP tool");
  const defs = schemaDefs("LeadCall");
  const timeout = defs.GatedRunCall?.properties?.timeoutSec?.maximum;
  if (typeof timeout !== "number") throw new Error("agent tools: gated_run's timeoutSec has no maximum");
  const gatedClasses: string[] = defs.GatedClass.enum;
  let md = "\n## Limits\n\nThe hub enforces these on every call, whatever an agent was told.\n\n";
  md += `- Only a lead starts agents (${codeList(new Set(spawners as string[]))}), and agents can't start their own.\n`;
  md += `- A lead has at most ${MAX_OPEN_TASKS} agents open at once, or twice the bot's max agents when that is more.\n`;
  md +=
    "- How many agents run at once is capped per bot (Max agents in the chat) and per machine (Settings › Hub › " +
    `Machines; unset, what the machine fits, at most ${HARD_TOP}). More wait and start by themselves. The lead doesn't count.\n`;
  md +=
    `- A command of class ${orList(gatedClasses.map((c) => `\`${c}\``))} goes through \`gated_run\`: it runs only after you approve it, for at ` +
    `most ${duration(timeout)}.\n\n`;
  md +=
    "These limits cover calls to fleetd, not the agent's own shell, which can do what your OS user can. See " +
    "[What an agent can reach](/docs/security#agent-reach).\n";
  return md;
}

/** Claude Code's built-in tools as the recorded version lists them, from the `system/init` lines in the runner's
 * recorded fixtures. */
function recordedTools(): string[] {
  const tools = new Set<string>();
  for (const name of readdirSync(FIXTURES)) {
    if (!name.startsWith(`claude-${RECORDED}-`) || !name.endsWith(".jsonl")) continue;
    for (const line of readFileSync(join(FIXTURES, name), "utf8").split("\n")) {
      let frame: Json;
      try {
        frame = JSON.parse(line);
      } catch {
        continue;
      }
      const msg = frame?.msg;
      if (msg?.type !== "system" || msg?.subtype !== "init" || !Array.isArray(msg.tools)) continue;
      for (const t of msg.tools) if (typeof t === "string" && !t.startsWith("mcp__")) tools.add(t);
    }
  }
  if (tools.size === 0) throw new Error(`agent tools: no claude ${RECORDED} init in ${FIXTURES}`);
  return [...tools].sort();
}

/** One list item per reason. A long run of Bash rules shows its first, with the rest folded away. */
function reasons(table: readonly (readonly [string, string])[], suffix = ""): string {
  let md = "";
  for (const [items, why] of grouped(ticked(table))) {
    const fold = items.length > 3 && items.every((i) => i.startsWith("`Bash("));
    const named = fold ? `${items[0]} and ${items.length - 1} more rules like it` : items.join(", ");
    md += `- ${named}${suffix}: ${sourceText(why)}\n`;
    if (fold) md += `\n  <details><summary>All ${items.length} rules</summary>\n\n  ${items.join(", ")}\n\n  </details>\n\n`;
  }
  return md;
}

function builtins(): string {
  const blocked = DISALLOWED_WHY.map(([t]) => t);
  // What an agent is offered: the tools fleetd's agents lose are listed with the reason below.
  const agentBlocked = AGENT_DISALLOWED_WHY.map(([t]) => t);
  const allowedTools = recordedTools().filter((t) => !blocked.includes(t) && !agentBlocked.includes(t) && !agentLike(t));
  let md = `\n## Claude Code tools\n\nAs listed by Claude Code ${RECORDED}. fleetd is tested with ${TESTED}.\n\n`;
  md += `**Allowed:** ${codeList(allowedTools)}.\n\n`;
  md += "A bot's [`.fleetd/policy.yaml`](/docs/config-and-files#policy) can block more with `tools.deny`.\n\n";
  md += "### Blocked everywhere\n\nNo session fleetd starts gets these, and your own settings can't turn them back on.\n\n";
  md += reasons(DISALLOWED_WHY);
  md +=
    "\nA tool like these that a newer Claude Code adds is blocked too: a session that still offers one is stopped, and " +
    "later sessions on that machine block it.\n\n### Blocked for fleetd's agents\n\nYour own threads keep these.\n\n";
  md += reasons(AGENT_DISALLOWED_WHY, " (leads and agents)");
  md += reasons(TASK_DISALLOWED_WHY, " (agents)");
  md += reasons(LEAD_DISALLOWED_WHY, " (leads with repos)");
  md +=
    "\n### What a lead does without asking\n\nA lead runs in Claude Code's `manual` permission mode, with no sandbox " +
    "([how leads run](/docs/security#how-leads-run)). Its shell commands run without asking, unless one would wipe the " +
    "machine. These run without asking too:\n\n";
  md += reasons(LEAD_ALLOWED_WHY);
  md += "\nThese go through the bot's approval mode first:\n\n";
  md += reasons(LEAD_ASK_WHY);
  return md;
}

