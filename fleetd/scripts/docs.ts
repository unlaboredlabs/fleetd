/** The help's layout: a group heading at column 0 ending in `:`, an entry at column 2 (its description may follow
 * after two spaces), synopsis continuations indented less than 13, descriptions at 13. */
export function parseHelp(help: string): Group[] {
  const groups: Group[] = [];
  for (const line of help.split("\n")) {
    const body = line.trimStart();
    if (!body || line.startsWith("usage:")) continue;
    const indent = line.length - body.length;
    if (indent === 0) {
      if (!body.endsWith(":")) throw new Error(`fleetd help: unexpected line ${JSON.stringify(line)}`);
      const title = body.slice(0, -1);
      groups.push({ title, id: slugify(title.split(" (")[0]!), entries: [] });
      continue;
    }
    const group = groups.at(-1);
    if (!group) throw new Error(`fleetd help: ${JSON.stringify(line)} before any group heading`);
    if (indent === 2) {
      const gap = body.indexOf("  ");
      const synopsis = gap < 0 ? body : body.slice(0, gap);
      const desc = gap < 0 ? [] : [body.slice(gap + 2).trim()];
      const name = commandWords(synopsis).join(" ");
      if (!name) throw new Error(`fleetd help: no command in ${JSON.stringify(line)}`);
      group.entries.push({ id: "", name, synopsis: [synopsis], desc });
      continue;
    }
    const entry = group.entries.at(-1);
    if (!entry) throw new Error(`fleetd help: ${JSON.stringify(line)} before any command`);
    if (indent >= 13) entry.desc.push(body);
    else entry.synopsis.push(body);
  }
  assignIds(groups);
  if (groups.reduce((n, g) => n + g.entries.length, 0) < 10) {
    throw new Error("fleetd help lists fewer than 10 commands; did its layout change?");
  }
  return groups;
}

/** `machine add <ssh-host> | --local …` -> ["machine", "add"]. */
function commandWords(synopsis: string): string[] {
  const words: string[] = [];
  for (const w of synopsis.split(/\s+/).filter(Boolean)) {
    if (!/^[a-z][a-z-]*$/.test(w)) break;
    words.push(w);
  }
  return words;
}

/** The command words joined by `-`; a repeated command adds its first option and that option's literal value:
 * `machine-add`, `pair-worker`, `hub-key-create-human`. */
function assignIds(groups: Group[]) {
  const seen = new Set<string>();
  for (const entry of groups.flatMap((g) => g.entries)) {
    let id = entry.name.replaceAll(" ", "-");
    if (seen.has(id)) {
      const words = entry.synopsis[0]!.split(/\s+/).filter(Boolean);
      const at = words.findIndex((w) => w.replace(/^[[(]+/, "").startsWith("--"));
      if (at >= 0) {
        id += `-${words[at]!.replace(/^[[(]+/, "").replace(/^-+/, "").replace(/[\])]+$/, "")}`;
        const value = words[at + 1];
        if (value !== undefined && /^[a-z]*$/.test(value)) id += `-${value}`;
      }
    }
    while (seen.has(id)) id += "_";
    seen.add(id);
    entry.id = id;
  }
}

const capitalize = (s: string) => s.slice(0, 1).toUpperCase() + s.slice(1);

const TRAILING = /[,;:.)"]+$/;
const trimTrailing = (s: string) => s.replace(TRAILING, "");

/** Description prose with machine text set as code: anything in backticks, `--options`, `~/paths`, and `fleetd`
 * followed by a command (one of `commands`, the first words) and its further words (`subcommands`, any command's). */
export function prose(text: string, commands: string[], subcommands: string[]): string {
  const isCode = (c: string) => (c.startsWith("--") && c.length > 2) || c.startsWith("~/");
  let out = "";
  text.split("`").forEach((part, i) => {
    if (i % 2 === 1) {
      out += `\`${part}\``;
      return;
    }
    const tokens = part.split(" ");
    let t = 0;
    while (t < tokens.length) {
      if (t > 0) out += " ";
      const token = tokens[t]!;
      const lead = token.length - token.replace(/^[("]+/, "").length;
      const coreEnd = Math.max(trimTrailing(token).length, lead);
      const [pre, core, post] = [token.slice(0, lead), token.slice(lead, coreEnd), token.slice(coreEnd)];
      const next = tokens[t + 1];
      const nextIsCommand = next !== undefined && commands.includes(trimTrailing(next));
      // "the fleetd version" is prose; "then fleetd doctor" names a command.
      const proseBefore = t > 0 && ["the", "this", "a"].includes(tokens[t - 1]!);
      if (core === "fleetd" && post === "" && nextIsCommand && !proseBefore) {
        // "fleetd pair --worker prints": the command words and options that follow, up to punctuation.
        const words = [core];
        let tail = "";
        let j = t + 1;
        for (; j < tokens.length; j++) {
          const n = tokens[j]!;
          const c = trimTrailing(n);
          if (tail || !(subcommands.includes(c) || isCode(c))) break;
          words.push(c);
          tail = n.slice(c.length);
        }
        out += `${mdText(pre)}\`${words.join(" ")}\`${mdText(tail)}`;
        t = j;
        continue;
      }
      out += isCode(core) ? `${mdText(pre)}\`${core}\`${mdText(post)}` : mdText(token);
      t++;
    }
  });
  return out;
}

export function cliPage(help: string = usageText()): string {
  const groups = parseHelp(help);
  const entries = groups.flatMap((g) => g.entries);
  const commands = entries.map((e) => e.name.split(" ")[0]!);
  // Every word of every command, for what follows the first: `fleetd hub key revoke`.
  const words = entries.flatMap((e) => e.name.split(" "));
  let md = CLI_INTRO;
  const seen = new Set<string>();
  for (const group of groups) {
    // "setting up (on the hub machine)" -> "Setting up", and the parenthesis as its first line.
    const paren = group.title.indexOf(" (");
    const short = paren < 0 ? group.title : group.title.slice(0, paren);
    const aside = paren < 0 ? undefined : group.title.slice(paren + 2).replace(/\)+$/, "");
    // Explicit ids keep the anchors (#machine-add, #hub-key-create-human) independent of the heading text.
    for (const id of [group.id, ...group.entries.map((e) => e.id)]) {
      if (seen.has(id)) throw new Error(`CLI reference: #${id} is used twice`);
      seen.add(id);
    }
    md += `\n## ${mdText(capitalize(short))} {#${group.id}}\n\n`;
    if (aside !== undefined) md += `${mdText(capitalize(aside))}.\n\n`;
    // `hub start` alone leaves a hub the other commands can't use; the docs walk through the order that works.
    if (group.id === "running-by-hand") {
      md +=
        ":::tip\nRun `fleetd init --no-service` before `fleetd hub start`: it writes the setup the other commands read. " +
        "The whole order is in [Run a second fleet on one machine](/docs/config-and-files#second-fleet).\n:::\n\n";
    }
    for (const entry of group.entries) {
      const synopsis = entry.synopsis.map((l, i) => (i === 0 ? `fleetd ${l}` : `    ${l}`));
      md += `### fleetd ${entry.name} {#${entry.id}}\n\n\`\`\`text\n${synopsis.join("\n")}\n\`\`\`\n\n`;
      if (entry.desc.length) md += `${prose(entry.desc.join(" "), commands, words)}\n\n`;
    }
  }
  return trimEnd(md);
}

