const PROMPT_GROUPS: [PromptGroup, string][] = [
  ["lead", "Lead"],
  ["tasks", "Tasks"],
  ["reviews_and_checks", "Reviews and checks"],
  ["messages", "Messages"],
];

/** One `###` per group, then a row per prompt with its id, when it is sent and the safety rules it carries
 * (prompt-only ones marked). */
export function promptTable(): string {
  let md = "";
  for (const [group, title] of PROMPT_GROUPS) {
    md += `### ${title}\n\n| Id | Sent | Safety rules |\n|---|---|---|\n`;
    for (const e of ENTRIES.filter((e) => e.group === group && e.id !== INSTRUCTIONS)) {
      const rules = safetyRules(e).map((r) => (r.enforced === "code" ? mdText(r.label) : `${mdText(r.label)} (prompt only)`));
      md += `| \`${e.id}\` | ${mdText(e.sentWhen)} | ${rules.join("; ")} |\n`;
    }
    md += "\n";
  }
  return trimEnd(md);
}

