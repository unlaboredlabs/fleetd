const schemaDefs = (name: string): Json => JSON.parse(readFileSync(join(SCHEMA, `${name}.json`), "utf8")).$defs;

function limits(lead: ToolSpec[], task: ToolSpec[]): string {
  const spawners: string[] = [];
  for (const op of SPAWN_OPS) {
    const tool = lead.find((t) => t.op === op);
    if (!tool) throw new Error("agent tools: a hub policy op has no MCP tool");
    if (!spawners.includes(tool.name)) spawners.push(tool.name);
  }
  // Every tool a task is offered: its lead calls, which the hub allows by WORKER_OPS, and its browser calls, which its
  // node answers.
  const refused = task.find((t) => !t.browser && !WORKER_OPS.includes(t.op));
  if (refused) throw new Error(`agent tools: a task is offered ${refused.name}, which the hub refuses it`);
  const defs = schemaDefs("LeadCall");
  const timeout = defs.GatedRunCall?.properties?.timeoutSec?.maximum;
  if (typeof timeout !== "number") throw new Error("agent tools: gated_run's timeoutSec has no maximum");
  const gatedClasses: string[] = defs.GatedClass.enum;
  let md =
    "## Hub limits\n\nThe hub checks these on every fleetd call a session makes, through its MCP tools or a `fleetd` command " +
    "in its shell. A refusal says why and what to do instead.\n\n| Limit | Value |\n|---|---|\n";
  md += `| Who can start agents | A lead, with ${codeList(spawners)}. A task's agent can't. |\n`;
  md += `| Depth | ${MAX_DEPTH}. A lead is depth 0 and its tasks depth ${MAX_DEPTH}; nothing goes deeper. |\n`;
  md += `| Open tasks per lead | ${MAX_OPEN_TASKS}, or twice the project's max agents when that is more (queued, running or idle). |\n`;
  md +=
    "| Agents running at once, per project | The project's max agents, which a person sets (`cap_set`, the chat's Max agents); " +
    "unset, its machine's cap within the fleet cap. A spawn over it queues and starts by itself; a review goes ahead of queued " +
    "writers. The lead is not an agent and doesn't count. |\n";
  md +=
    "| Agents running at once, per machine | The machine's max agents, which a person may set up to the fleet cap (`cap_set`, " +
    "`fleetd machine set`, Settings › Hub › Machines). Unset: what the machine fits, one per CPU less one in eight, and 2 GB of " +
    `memory each after a quarter (4 to 16 GB) is left for the system, at most ${HARD_TOP}. Either way new agents wait for 5 GB ` +
    "of disk each above the free-space floor; load and memory never hold them back. |\n";
  md += "| Agents running at once, fleet-wide | The machines' caps added up, unless a person set a fleet cap. |\n";
  md += `| Calls a task's agent may make | ${codeList(task.map((t) => t.name))}. Every other call is refused. |\n`;
  md += `| Gated commands (\`gated_run\`) | Classes ${codeList(gatedClasses)}. Run only after a human approves; at most ${timeout} s. |\n`;
  md += "\n";
  md +=
    "These limits cover calls to fleetd, not what the agent's own shell can do. A task runs with full Bash, so `gated_run` is " +
    "not the only way it could run a command. A process that leaves its session's process tree (for example with `setsid`) " +
    "and scrubs its environment counts as you, with no limits: see \"Known limit\" on the Security page. Run agents you don't " +
    "trust as a different OS user.\n\n";
  return md;
}

/** The roles that are offered a tool making call `op` and that the hub lets make it. */
function whoMayCall(tool: ToolSpec): string {
  const who: string[] = [];
  for (const [role, caller, name] of [
    ["lead", { kind: "lead" }, "a lead"],
    ["worker", TASK_CALLER, "a task's agent"],
  ] as [Role, CallerAgent, string][]) {
    // A browser call never reaches the hub's policy: the session's own node answers it.
    if (toolsFor(role).some((t) => t.op === tool.op) && (tool.browser || allowed(caller, tool.op))) who.push(name);
  }
  return who.join(", ");
}

function toolSection(title: string, intro: string, role: Role, tools: ToolSpec[], taken: string[]): string {
  // A task tool that has a lead namesake says so, so each heading is unique on the page.
  const heading = (tool: ToolSpec) => (taken.includes(tool.name) ? `${tool.name} (task)` : tool.name);
  let md = `## ${title}\n\n${intro}\n\n| Tool | What it does | Needs a human |\n|---|---|---|\n`;
  for (const tool of tools) {
    md += `| [\`${tool.name}\`](#${slugify(heading(tool))}) | ${cell(firstSentence(tool.description))} | ${cell(HUMAN[tool.name] ?? "No")} |\n`;
  }
  md += "\n";
  for (const tool of tools) {
    md += `### ${heading(tool)}\n\n${sourceText(tool.description)}\n\n`;
    const rows = params(tool.inputSchema, "");
    if (rows.length === 0) {
      md += "No parameters.\n\n";
    } else {
      md += "| Parameter | Type | Required | Description |\n|---|---|---|---|\n";
      for (const row of rows) md += `| \`${row.name}\` | ${row.ty} | ${row.required ? "yes" : "no"} | ${cell(row.description)} |\n`;
      md += "\n";
    }
    const checked = tool.browser ? "answered by its node, which runs the browser" : "checked by the hub";
    md += `**Who may call:** ${whoMayCall(tool)}, ${checked}. **Needs a human:** ${HUMAN[tool.name] ?? "no."}\n\n`;
    const args = example(role, tool.name);
    if (args === undefined) throw new Error(`agent tools: ${tool.name} has no example call`);
    checkExample(role, tool, args);
    const pretty = JSON.stringify(sorted(args), null, 2).replaceAll("\n", "\n  ");
    md += `\`\`\`json\n{\n  "name": "${tool.name}",\n  "arguments": ${pretty}\n}\n\`\`\`\n\n`;
  }
  return md;
}

function firstSentence(text: string): string {
  const i = text.indexOf(". ");
  return i < 0 ? text : text.slice(0, i + 1);
}

type Param = { name: string; ty: string; required: boolean; description: string };

const isObj = (v: Json): v is Record<string, Json> => v !== null && typeof v === "object" && !Array.isArray(v);
const variantsOf = (s: Json): Json[] | undefined => (Array.isArray(s?.oneOf) ? s.oneOf : Array.isArray(s?.anyOf) ? s.anyOf : undefined);
const enumValues = (s: Json): string[] => (Array.isArray(s?.enum) ? s.enum.filter((v: Json) => typeof v === "string") : []);

/** One row per property, nested objects and arrays of objects flattened as `a.b` and `a[].b`. */
function params(schema: Json, prefix: string, rows: Param[] = []): Param[] {
  const required: string[] = Array.isArray(schema?.required) ? schema.required : [];
  if (!isObj(schema?.properties)) return rows;
  for (const [key, prop] of Object.entries(schema.properties as Record<string, Json>)) {
    const name = `${prefix}${key}`;
    rows.push({ name, ty: typeOf(prop), required: required.includes(key), description: describe(prop) });
    if (isObj(prop?.properties)) params(prop, `${name}.`, rows);
    else if (isObj(prop?.items?.properties)) params(prop.items, `${name}[].`, rows);
  }
  return rows;
}

function typeOf(prop: Json): string {
  if (typeof prop?.type === "string") return prop.type === "array" ? `${typeOf(prop.items)}[]` : prop.type;
  const types = [...new Set((variantsOf(prop) ?? []).map(typeOf))].sort();
  return types.length === 0 ? "any" : types.join(" or ");
}

const isInt = (v: Json) => typeof v === "number" && Number.isInteger(v) && v >= 0;

/** The property's own description, cleaned of source-code notation, then its constraints in words. */
function describe(prop: Json): string {
  const parts: string[] = [];
  const own = typeof prop?.description === "string" ? prop.description : undefined;
  if (own !== undefined) parts.push(clean(own));
  const values = enumValues(prop);
  if (values.length) parts.push(`One of ${codeList(values)}.`);
  const variants = variantsOf(prop);
  if (variants) {
    const consts = variants.flatMap((v) => {
      const e = enumValues(v);
      const c = typeof v?.const === "string" ? v.const : e.length === 1 ? e[0] : undefined;
      if (c === undefined) return [];
      return [typeof v.description === "string" ? `\`${c}\` (${v.description.replace(/\.+$/, "")})` : `\`${c}\``];
    });
    const shapes = variants.filter((v) => isObj(v?.properties)).map((v) => `{${Object.keys(v.properties).join(", ")}}`);
    if (consts.length && consts.length === variants.length) parts.push(`One of ${consts.join(", ")}.`);
    if (shapes.length) parts.push(`One of these shapes: ${shapes.join("; ")}.`);
    if (prop.description == null) {
      for (const v of variants) {
        if (v?.const == null && enumValues(v).length === 0 && typeof v?.description === "string") parts.push(clean(v.description));
      }
    }
  }
  if (prop?.description == null && typeof prop?.pattern === "string") parts.push(patternWords(prop.pattern));
  if (isInt(prop?.maxLength)) parts.push(`At most ${prop.maxLength} characters.`);
  if (isInt(prop?.maxItems)) parts.push(`At most ${prop.maxItems} items.`);
  const [min, max] = [prop?.minimum, prop?.maximum];
  if (typeof min === "number" && typeof max === "number" && max < 1e12) parts.push(`${min} to ${max}.`);
  else if (typeof min === "number" && min > 0) parts.push(`At least ${min}.`);
  if (isObj(prop) && "default" in prop && !(Array.isArray(prop.default) && prop.default.length === 0)) {
    parts.push(`Default \`${JSON.stringify(sorted(prop.default))}\`.`);
  }
  return parts.filter((p) => p !== "").join(" ");
}

/** `^T[1-9][0-9]*$` reads as "`T<n>`, e.g. `T1`". */
export function patternWords(pattern: string): string {
  const letter = /^\^(.)\[1-9\]\[0-9\]\*\$$/u.exec(pattern)?.[1];
  if (letter !== undefined) return `\`${letter}<n>\`, e.g. \`${letter}1\`.`;
  if (pattern === "^[^\\r\\n]*$") return "One line.";
  if (pattern === "^/") return "An absolute path.";
  return `Matches \`${pattern}\`.`;
}

/** Doc comments are written for the source: drop rustdoc links, a CLI flag prefix and milestone tags. */
export function clean(source: string): string {
  let text = source.replaceAll("[`", "`").replaceAll("`]", "`");
  if (text.startsWith("`--")) {
    const i = text.indexOf("`: ");
    if (i >= 0) text = text.slice(i + 3);
  }
  const milestone = /^M(\d*): /.exec(text);
  if (milestone) text = text.slice(milestone[0].length);
  if (text.startsWith("https://") && !text.includes(" ")) return `Like \`${text}\`.`;
  const first = text.codePointAt(0);
  if (first !== undefined) {
    const c = String.fromCodePoint(first);
    text = c.toUpperCase() + text.slice(c.length);
  }
  return text.endsWith(".") || text.endsWith(")") ? text : `${text}.`;
}

